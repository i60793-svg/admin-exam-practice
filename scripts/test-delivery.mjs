import fs from 'node:fs';
import assert from 'node:assert/strict';
import vm from 'node:vm';
const source=fs.readFileSync('worker/index.js','utf8');
const worker=(await import('data:text/javascript;base64,'+Buffer.from(source).toString('base64'))).default;
const fetchPath=(path,headers={},method='GET')=>worker.fetch(new Request('https://example.test'+path,{headers,method}),{});
const page=await fetchPath('/');
assert.equal(page.headers.get('cache-control'),'private, no-cache');
const html=await page.text();
const bankPath=html.match(/fetch\("([^"]+)"\)/)[1];
const scriptPath=html.match(/src="(\/app\.[^"]+\.js)"/)[1];
assert.ok(html.includes('globalThis.__BANK_REQUEST'));
for(const path of ['/',bankPath,scriptPath]){
 const raw=await fetchPath(path);const body=await raw.text();
 if(path!=='/')assert.match(raw.headers.get('cache-control'),/immutable/);
 const compressed=await fetchPath(path,{'Accept-Encoding':'br, gzip'});
 assert.equal(compressed.headers.get('content-encoding'),null);
 assert.equal(await compressed.text(),body);
 assert.match(compressed.headers.get('content-type'),/charset=utf-8/);
 const disabled=await fetchPath(path,{'Accept-Encoding':'gzip;q=0'});
 assert.equal(disabled.headers.get('content-encoding'),null);
 const cached=await fetchPath(path,{'If-None-Match':raw.headers.get('etag')});
 assert.equal(cached.status,304);assert.equal(await cached.text(),'');
 const head=await fetchPath(path,{},'HEAD');assert.equal(await head.text(),'');
}
const packed=await (await fetchPath(bankPath)).json();
const client=fs.readFileSync('client.js','utf8');
const decode=client.match(/function decodeBank\(d\)[\s\S]*?(?=\nasync function init)/)[0];
const context=vm.createContext({});vm.runInContext(decode,context);
context.packed=packed;
const decoded=JSON.parse(JSON.stringify(vm.runInContext('decodeBank(packed)',context)));
const active=JSON.parse(fs.readFileSync('data/current-subjects.json'));
const translations=JSON.parse(fs.readFileSync('data/english-translations.json'));
const questions=JSON.parse(fs.readFileSync('data/questions.json')).filter(q=>active.includes(q.subject)).map(q=>translations[q.id]?{...q,translation:translations[q.id]}:q);
const papers=JSON.parse(fs.readFileSync('data/papers.json')).filter(p=>active.some(s=>p.subject===s||p.subject.startsWith(s+'（')));
assert.deepEqual(decoded,{papers,questions});
assert.deepEqual(await (await fetchPath('/api/bank')).json(),decoded);
assert.equal(await (await fetchPath('/app.js')).text(),await (await fetchPath(scriptPath)).text());
assert.equal((await fetchPath('/api/bank.missing.json')).status,404);
console.log('PASS: full bank and translation equivalence, UTF-8 text regardless of compression request, version caches, ETag 304, HEAD, early fetch and legacy URLs.');
